SET NOCOUNT ON;

IF OBJECT_ID(N'dbo.CHANNEL_COLLECTION_RUN', N'U') IS NULL
    THROW 51000, 'CHANNEL_COLLECTION_RUN is missing', 1;
IF OBJECT_ID(N'dbo.CHANNEL_COLLECTION_ATTEMPT', N'U') IS NULL
    THROW 51000, 'CHANNEL_COLLECTION_ATTEMPT is missing', 1;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.CHANNEL_COLLECTION_RUN') AND name = N'IX_CHANNEL_COLLECTION_RUN_SCHEDULED_STATUS')
    THROW 51000, 'IX_CHANNEL_COLLECTION_RUN_SCHEDULED_STATUS is missing', 1;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.CHANNEL_COLLECTION_ATTEMPT') AND name = N'IX_CHANNEL_COLLECTION_ATTEMPT_CHANNEL_STATUS')
    THROW 51000, 'IX_CHANNEL_COLLECTION_ATTEMPT_CHANNEL_STATUS is missing', 1;

SELECT N'CHANNEL_COLLECTION_RUN' AS ObjectName, COUNT_BIG(*) AS [row_count] FROM dbo.CHANNEL_COLLECTION_RUN
UNION ALL
SELECT N'CHANNEL_COLLECTION_ATTEMPT', COUNT_BIG(*) FROM dbo.CHANNEL_COLLECTION_ATTEMPT;
